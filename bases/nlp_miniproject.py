def get_raw_text_from_file(file_name, file_bytes):
    """
    Extracts raw text from a file (PDF or DOCX), using OCR if necessary.
    """
    text = ""
    try:
        if file_name.lower().endswith('.pdf'):
            with fitz.open(stream=file_bytes, filetype="pdf") as doc:
                text = "".join(page.get_text() for page in doc)

            # If no text layer, it's an image-based PDF; run OCR
            if not text.strip():
                print("INFO: No text layer found. Running OCR...")
                with fitz.open(stream=file_bytes, filetype="pdf") as doc:
                    for page in doc:
                        pix = page.get_pixmap(dpi=300)
                        img = Image.open(io.BytesIO(pix.tobytes()))
                        text += pytesseract.image_to_string(img)

        elif file_name.lower().endswith('.docx'):
            doc = docx.Document(io.BytesIO(file_bytes))
            text = "\n".join([para.text for para in doc.paragraphs])

    except Exception as e:
        print(f"ERROR: Could not parse file '{file_name}': {e}")

    return text.strip()



