# PDF Processing

def extract_pdf_text_pymupdf(file_path):
    """Extracts text from a PDF's text layer using PyMuPDF."""
    try:
        with fitz.open(file_path) as doc:
            text = "".join(page.get_text() for page in doc)
        return text.strip()
    except Exception as e:
        print(f"  Error extracting text with PyMuPDF: {e}")
        return None

def perform_ocr_on_pdf(file_path):
    """Performs OCR on a PDF, treating each page as an image."""
    print("\n### Text (from OCR Tesseract):")
    try:
        doc = fitz.open(file_path)
        full_text = ""
        for page in doc:
            pix = page.get_pixmap(dpi=300)  # Render page to an image
            img = Image.open(io.BytesIO(pix.tobytes()))
            text = pytesseract.image_to_string(img)
            full_text += text + "\n"
        print(full_text or "OCR did not find any text.")
    except Exception as e:
        print(f"  Error during OCR: {e}")

def extract_pdf_images(file_path):
    """Extracts embedded images from a PDF."""
    print("\n### Embedded Images:")
    try:
        doc = fitz.open(file_path)
        image_found = False
        for page_num, page in enumerate(doc):
            for img_index, img in enumerate(page.get_images(full=True)):
                xref = img[0]
                base_image = doc.extract_image(xref)
                image_bytes = base_image["image"]
                image = Image.open(io.BytesIO(image_bytes))
                saved_path = f"extracted_{file_path}_p{page_num+1}_img{img_index+1}.png"
                image.save(saved_path)
                print(f"  Image saved as '{saved_path}'")
                image_found = True
        if not image_found:
            print("  No embedded images found.")
    except Exception as e:
        print(f"  Error extracting images: {e}")

def extract_pdf_tables(file_path):
    """Extracts tables from a PDF using tabula-py."""
    print("\n### Tables:")
    try:
        tables = tabula.read_pdf(file_path, pages='all', silent=True)
        if tables:
            print(f"  Found {len(tables)} table(s).")
            for i, df in enumerate(tables):
                print(f"\n--- Table {i+1} ---")
                display(df)
        else:
            print("  No tables found.")
    except Exception as e:
        print(f"  Error extracting tables: {e}")

#Docx Processing
def extract_docx_text(doc):
    """Extracts all paragraph text from a DOCX document."""
    print("### Text:")
    try:
        full_text = [para.text for para in doc.paragraphs]
        print('\n'.join(full_text) or "No text found in paragraphs.")
    except Exception as e:
        print(f"  Error extracting text: {e}")

def extract_docx_tables(doc):
    """Extracts tables from a DOCX document."""
    print("\n### Tables:")
    try:
        if doc.tables:
            print(f"  Found {len(doc.tables)} table(s).")
            for i, table in enumerate(doc.tables):
                print(f"\n--- Table {i+1} ---")
                data = [[cell.text for cell in row.cells] for row in table.rows]
                df = pd.DataFrame(data[1:], columns=data[0] if data else None)
                display(df)
        else:
            print("  No tables found.")
    except Exception as e:
        print(f"  Error extracting tables: {e}")

def extract_docx_images(doc, file_name):
    """Extracts images from a DOCX document."""
    print("\n### Images:")
    try:
        image_found = False
        image_parts = [part for rel in doc.part.rels.values() if "image" in rel.target_ref for part in (rel.target_part,)]
        for i, image_part in enumerate(image_parts):
            image_bytes = image_part.blob
            image = Image.open(io.BytesIO(image_bytes))
            saved_path = f"extracted_{file_name}_img{i+1}.{image.format.lower()}"
            image.save(saved_path)
            print(f"  Image saved as '{saved_path}'")
            image_found = True
        if not image_found:
            print("  No images found.")
    except Exception as e:
        print(f"  Error extracting images: {e}")


def process_pdf(file_name):
    """Manages the extraction process for a PDF file, with OCR fallback."""
    print(f"\n--- Processing PDF: {file_name} ---")

    # First, try to extract text from the text layer
    print("### Text (from PyMuPDF):")
    standard_text = extract_pdf_text_pymupdf(file_name)
    print(standard_text or "No text layer found.")

    # If no text was found, it's likely an image-based PDF, so run OCR
    if not standard_text:
        perform_ocr_on_pdf(file_name)

    # Proceed with table and image extraction
    extract_pdf_tables(file_name)
    extract_pdf_images(file_name)

def process_docx(file_name):
    """Manages the extraction process for a DOCX file."""
    print(f"\n--- Processing DOCX: {file_name} ---")
    try:
        doc = docx.Document(file_name)
        extract_docx_text(doc)
        extract_docx_tables(doc)
        extract_docx_images(doc, file_name)
    except Exception as e:
        print(f"Failed to open and process DOCX file. Error: {e}")

